class Citation(BaseModel):
    """
    Verified citation matching frontend Citation interface:
    export interface Citation { rank: number; file: string; line: string; page: string; text: string; verified: boolean; }
    """
    model_config = ConfigDict(extra="ignore")

    rank: int
    file: str
    line: str = "N/A"
    page: str = "N/A"
    text: str
    verified: bool = True
    evidence_id: Optional[str] = None
    entity_id: Optional[str] = None


class RetrievedSnippet(BaseModel):
    """
    Retrieved snippet matching frontend RetrievedSnippet interface:
    export interface RetrievedSnippet { id: string; rank: number; text: string; file: string; line: string; score: number; }
    """
    model_config = ConfigDict(extra="ignore")

    id: str
    rank: int
    text: str
    file: str
    line: str = "N/A"
    page: Optional[str] = "N/A"
    score: float = 0.0
    modality: Optional[str] = "vector"


class CopilotResponse(BaseModel):
    """
    Complete Copilot response matching frontend CopilotResponse interface:
    export interface CopilotResponse {
        answer: string;
        citations: Citation[];
        retrieved_snippets?: RetrievedSnippet[];
        model_used: string;
        is_generated?: boolean;
        abstained?: boolean;
        warning?: string | null;
    }
    """
    model_config = ConfigDict(extra="ignore", protected_namespaces=())

    answer: str
    citations: List[Citation] = Field(default_factory=list)
    retrieved_snippets: List[RetrievedSnippet] = Field(default_factory=list)
    model_used: str
    is_generated: bool = True
    abstained: bool = False
    warning: Optional[str] = None
    verification: Optional[Dict[str, Any]] = None
    query_plan: Optional[Dict[str, Any]] = None
    mutation_proposals: List[Dict[str, Any]] = Field(default_factory=list)
