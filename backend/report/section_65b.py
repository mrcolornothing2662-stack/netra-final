async def generate_65b_pdf(
    case_id:    str,
    db:         AsyncSession,
    officer_id: str | None = None,
) -> str:
    """
    Generate a Section 65B analysis-aid PDF for the given case.
    Returns the path to the generated PDF file.
    """
    # UUID columns bind via value.hex on SQLite — a raw path string 500s
    # ('str' object has no attribute 'hex'). Coerce once here; AuditLog.resource_id
    # is Text (stores the string form) so that lookup keeps the original string.
    try:
        case_uuid = case_id if isinstance(case_id, uuid.UUID) else uuid.UUID(str(case_id))
    except (ValueError, AttributeError, TypeError):
        raise ValueError(f"Case {case_id} not found")

    # Fetch case
    case = await db.get(Case, case_uuid)
    if not case:
        raise ValueError(f"Case {case_id} not found")

    # Fetch evidence files
    ev_files = (await db.execute(
        select(EvidenceFile).where(EvidenceFile.case_id == case_uuid)
    )).scalars().all()

    # Fetch entities
    entities = (await db.execute(
        select(Entity).where(Entity.case_id == case_uuid)
    )).scalars().all()

    # Fetch flagged correlations
    correlations = (await db.execute(
        select(Correlation).where(
            Correlation.case_id == case_uuid,
            Correlation.decision == "flagged",
        )
    )).scalars().all()

    # Fetch unified findings (verified intelligence output)
    findings = (await db.execute(
        select(InvestigationFinding)
        .where(InvestigationFinding.case_id == case_uuid)
        .order_by(InvestigationFinding.confidence.desc(), InvestigationFinding.created_at.desc())
    )).scalars().all()

    # Fetch audit entries
    audit_entries = (await db.execute(
        select(AuditLog)
        .where(AuditLog.resource_id == case_id)
        .order_by(AuditLog.id.desc())
        .limit(50)
    )).scalars().all()

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")

    # Render HTML
    from jinja2 import Environment
    env  = Environment()
    env.globals["str"] = str
    tmpl = env.from_string(_TEMPLATE_HTML)
    html_content = tmpl.render(
        case=case,
        evidence_files=ev_files,
        entities=entities,
        entity_count=len(entities),
        correlations=correlations,
        link_count=len(correlations),
        findings=findings,
        finding_count=len(findings),
        audit_entries=audit_entries,
        generated_at=generated_at,
        version="1.0.0",
    )

    # Generate PDF. Prefer the richer HTML rendition where the native
    # WeasyPrint dependencies are present, otherwise use the portable fallback.
    pdf_path = REPORT_DIR / f"65B_{case.case_number.replace('/', '_')}_{case_id[:8]}.pdf"
    if HTML is not None:
        HTML(string=html_content).write_pdf(str(pdf_path))
    else:
        _write_reportlab_pdf(
            pdf_path, case, ev_files, entities, correlations, findings, audit_entries, generated_at
        )

    return str(pdf_path)


def _write_reportlab_pdf(pdf_path, case, evidence_files, entities, correlations, findings, audit_entries, generated_at):
    """Portable Section 65B analysis-aid PDF when WeasyPrint is unavailable."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib import colors

    styles = getSampleStyleSheet()
    body = styles["BodyText"]
    story = [
        Paragraph("CyberDrishti AI - Investigation Evidence Certificate", styles["Title"]),
        Paragraph("Analysis aid only; not a replacement for a Section 65B device-custodian certificate.", body),
        Spacer(1, 5 * mm),
        Paragraph("1. Case Information", styles["Heading2"]),
        Table([
            ["Case number", case.case_number, "Status", case.status.upper()],
            ["Title", case.title, "Generated", generated_at],
        ], colWidths=[30 * mm, 65 * mm, 30 * mm, 55 * mm]),
        Spacer(1, 5 * mm),
        Paragraph("2. Evidence File SHA-256 Hash Table", styles["Heading2"]),
    ]
    evidence_rows = [["Filename", "Type", "Status", "SHA-256"]]
    evidence_rows.extend([
        [f.original_name, f.file_type.upper(), f.upload_status.upper(), f.sha256_hash]
        for f in evidence_files
    ] or [["No evidence files ingested.", "", "", ""]])
    story.append(Table(evidence_rows, repeatRows=1, colWidths=[45 * mm, 20 * mm, 25 * mm, 90 * mm]))
    story.extend([Spacer(1, 5 * mm), Paragraph(f"3. Extracted Entities ({len(entities)} total)", styles["Heading2"])])
    entity_rows = [["Type", "Canonical Value", "Bridge Score"]]
    entity_rows.extend([[e.entity_type, e.canonical_value, f"{(e.bridge_score or 0):.3f}"] for e in entities[:50]] or [["No entities extracted.", "", ""]])
    story.append(Table(entity_rows, repeatRows=1, colWidths=[35 * mm, 105 * mm, 30 * mm]))
    story.extend([Spacer(1, 5 * mm), Paragraph(f"4. Flagged Hidden Links ({len(correlations)} total)", styles["Heading2"])])
    story.extend([Spacer(1, 5 * mm), Paragraph(f"5. Unified Findings ({len(findings)} total)", styles["Heading2"])])
    finding_rows = [["Type", "Severity", "Confidence", "Title", "Engine", "Status"]]
    finding_rows.extend([
        [
            f.finding_type,
            f.severity,
            f"{(f.confidence or 0) * 100:.0f}%" if f.confidence is not None else "-",
            (f.title or "")[:80],
            f.source_engine or "-",
            f.status,
        ]
        for f in findings
    ] or [["No findings recorded.", "", "", "", "", ""]])
    story.append(Table(finding_rows, repeatRows=1, colWidths=[35 * mm, 20 * mm, 22 * mm, 70 * mm, 30 * mm, 23 * mm]))
    story.extend([Spacer(1, 5 * mm), Paragraph(f"Audit entries included: {len(audit_entries)}", body)])
    document = SimpleDocTemplate(str(pdf_path), pagesize=A4, rightMargin=15 * mm, leftMargin=15 * mm)
    for table in (item for item in story if isinstance(item, Table)):
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8eef6")),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
        ]))
    document.build(story)
